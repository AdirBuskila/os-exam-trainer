/* =============================================================================
   video-ui.js — "🎬 Video course": one narrated Hebrew video per guided level (ported from networks-quiz).
   Data: window.VIDEO_COURSE from videos.js (generated by tools/video/build_manifest.py — do not hand-edit it).
     {courses:[{id, title, icon, videos:[{id, level, title, minutes?, youtube?, bonus?}]}]}
     `level` is the guided level id ("sched-3", js/courses.js), `id` the video id (S03).
   Routes (app.js render()): #videos -> list, #video/<ID> -> player. Deep links ?video=<ID> and ?videos=1.
   Player: a YouTube id -> youtube-nocookie embed; otherwise the local MP4 (videos/out/<ID>/<ID>.mp4, present only
   when the owner runs the site from a checkout with rendered videos); if that fails, a "not uploaded yet" note.
   The videos are Hebrew only: in English mode the titles keep their Hebrew text (dir=rtl) with a "Hebrew" tag.
   Watched marks: localStorage os_trainer_video_v1 = {watched:{<ID>: timestamp}}, apart from the flashcard state.
   Public API (window.VIDEO_UI): list(view), play(id, view), lessonButtons(levelId), homeCard(), all.
   ============================================================================= */
(function (root, doc) {
'use strict';

var DATA = root.VIDEO_COURSE && Array.isArray(root.VIDEO_COURSE.courses) ? root.VIDEO_COURSE : { courses: [] };
var ALL = [];
DATA.courses.forEach(function (c) { (c.videos || []).forEach(function (v) { ALL.push(Object.assign({ course: c }, v)); }); });
var KEY = 'os_trainer_video_v1';
var from = null;                         // {levelId} when the player was opened from a guided lesson

function T(k, p) { return root.I18N ? root.I18N.t(k, p) : k; }
function he() { return root.I18N && root.I18N.lang === 'he'; }
function esc(s) { return String(s == null ? '' : s).replace(/[&<>"]/g, function (c) { return { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]; }); }
function iso(s) { return root.I18N ? root.I18N.autoIsolate(s) : esc(s); }
function byId(id) { for (var i = 0; i < ALL.length; i++) if (ALL[i].id === id) return ALL[i]; return null; }
function courseOf(v) { return root.COURSES && root.COURSES[v.course.id]; }
function courseTitle(c) {                // the app's own (en/he) course title; the manifest's is Hebrew only
  var C = root.COURSES && root.COURSES[c.id];
  return C ? (he() ? C.title.he : C.title.en) : c.title;
}
function levelOf(v) {
  var C = courseOf(v);
  if (!C) return null;
  for (var i = 0; i < C.levels.length; i++) if (C.levels[i].id === v.level) return C.levels[i];
  return null;
}
/* a Hebrew video title: always RTL; in English mode tagged as Hebrew */
function vTitle(v) {
  return '<span dir="rtl" lang="he">' + iso(v.title) + '</span>' + (he() ? '' : ' <span class="vid-tag he">' + T('vid.hebrew') + '</span>');
}

/* ---------- progress ---------- */
function load() {
  try { var p = JSON.parse(localStorage.getItem(KEY)); if (p && p.watched && typeof p.watched === 'object') return p; } catch (e) {}
  return { watched: {} };
}
var prog = load();
function save() { try { localStorage.setItem(KEY, JSON.stringify(prog)); } catch (e) {} }
function watched(id) { return !!prog.watched[id]; }
function setWatched(id, on) { if (on) prog.watched[id] = Date.now(); else delete prog.watched[id]; save(); }
function nWatched() { return ALL.filter(function (v) { return watched(v.id); }).length; }

function minTxt(v) { return v.minutes ? T('vid.min', { n: v.minutes }) : ''; }
// not on YouTube yet: on the live site there is no local MP4 either, so the list says "soon"
function soon(v) { return !v.youtube && root.location.protocol !== 'file:'; }
function setHash(h) { try { history.replaceState(null, '', '#' + h); } catch (e) { root.location.hash = h; } }

/* ---------- list ---------- */
function list(view) {
  from = null;
  view = view || doc.getElementById('view');
  var nW = nWatched();
  var h = '<div class="card"><h2 class="sec">' + T('vid.title') + '</h2><p class="progresshint">' + T('vid.sub') + '</p>' +
    (he() ? '' : '<p class="vid-henote">🇮🇱 ' + T('vid.heNote') + '</p>') +
    '<div class="vid-overall">' + T('vid.watchedOf', { n: nW, m: ALL.length }) +
    '<div class="bar"><i style="width:' + (ALL.length ? Math.round(100 * nW / ALL.length) : 0) + '%"></i></div></div></div>' +
    '<div class="vid-courses">' + DATA.courses.filter(function (c) { return (c.videos || []).length; }).map(function (c) {
      var n = c.videos.filter(function (v) { return watched(v.id); }).length;
      return '<section class="card vid-course" data-course="' + esc(c.id) + '">' +
        '<h3 class="vid-course-h"><span' + (he() ? ' dir="rtl"' : '') + '>' + esc(c.icon || '') + ' ' + iso(courseTitle(c)) + '</span>' +
        '<span class="vid-count" dir="ltr">' + n + '/' + c.videos.length + '</span></h3><div class="vid-list">' +
        c.videos.map(function (v) {
          var w = watched(v.id);
          return '<button type="button" class="vid-row' + (w ? ' watched' : '') + (soon(v) ? ' soon' : '') + '" data-vid="' + esc(v.id) + '">' +
            '<span class="vid-num" dir="ltr">' + esc(v.id) + '</span>' +
            '<span class="vid-ttl">' + vTitle(v) + (soon(v) ? ' <span class="vid-tag soon">' + T('vid.soon') + '</span>' : '') + '</span>' +
            '<span class="vid-meta">' + minTxt(v) + '</span>' +
            '<span class="vid-check" aria-label="' + T(w ? 'vid.watchedMark' : 'vid.notWatchedMark') + '">' + (w ? '✓' : '▶') + '</span></button>';
        }).join('') + '</div></section>';
    }).join('') + '</div>' +
    '<div class="row" style="margin-top:12px"><button class="btn ghost" id="vidHomeBtn" onclick="go(\'home\')">' + T('vid.toHome') + '</button></div>';
  view.innerHTML = h;
  view.querySelectorAll('.vid-row').forEach(function (b) { b.onclick = function () { open(b.getAttribute('data-vid')); }; });
}

/* ---------- player ---------- */
function notUploaded() {
  return '<div class="vid-missing"><div class="vid-missing-ico">🎬</div><b>' + T('vid.notUploaded') + '</b><span>' + T('vid.notUploadedSub') + '</span></div>';
}
function mountMedia(v) {
  var f = doc.getElementById('vidFrame');
  function yt() {
    f.classList.remove('missing');
    f.innerHTML = '<iframe src="https://www.youtube-nocookie.com/embed/' + encodeURIComponent(v.youtube) + '?rel=0" title="' + esc(v.title) + '"' +
      ' allow="accelerometer; autoplay; clipboard-write; encrypted-media; gyroscope; picture-in-picture; web-share"' +
      ' referrerpolicy="strict-origin-when-cross-origin" allowfullscreen></iframe>';
  }
  // from file:// YouTube refuses the embed (no referrer, error 153): there the local MP4 goes first
  if (v.youtube && root.location.protocol !== 'file:') { yt(); return; }
  f.innerHTML = '<video controls preload="metadata" playsinline src="videos/out/' + encodeURIComponent(v.id) + '/' + encodeURIComponent(v.id) + '.mp4"></video>';
  var el = f.querySelector('video');
  el.addEventListener('error', function () {
    if (!doc.getElementById('vidFrame') || f.getAttribute('data-vid') !== v.id) return;
    if (v.youtube) yt(); else { f.classList.add('missing'); f.innerHTML = notUploaded(); }
  });
  el.addEventListener('ended', function () { setWatched(v.id, true); paintWatch(v); });
}
function paintWatch(v) {
  var b = doc.getElementById('vidWatchBtn'); if (!b) return;
  var on = watched(v.id);
  b.textContent = T(on ? 'vid.watched' : 'vid.markWatched');
  b.classList.toggle('on', on);
}
function play(id, view) {
  var v = byId(id);
  if (!v) return list(view);
  view = view || doc.getElementById('view');
  var i = ALL.indexOf(v), prev = ALL[i - 1], next = ALL[i + 1], L = levelOf(v);
  if (from && from.levelId !== v.level) from = null;
  var h = '<div class="card vid-player">' +
    '<div class="row crs-head"><span class="chip soft">' + esc(v.course.icon || '') + ' <span' + (he() ? ' dir="rtl"' : '') + '>' + iso(courseTitle(v.course)) + '</span></span>' +
    '<span class="chip soft" dir="ltr">' + esc(v.id) + '</span>' + (v.minutes ? '<span class="chip soft">' + minTxt(v) + '</span>' : '') + '</div>' +
    '<h2 class="vid-title">' + vTitle(v) + '</h2>' +
    '<div id="vidFrame" class="vid-frame" data-vid="' + esc(v.id) + '"></div>' +
    (v.youtube ? '<div class="vid-ytlink"><a href="https://www.youtube.com/watch?v=' + encodeURIComponent(v.youtube) + '" target="_blank" rel="noopener">' + T('vid.onYoutube') + '</a></div>' : '') +
    '<div class="vid-nav">' +
    '<button id="vidPrev" class="btn ghost" type="button"' + (prev ? ' title="' + esc(prev.title) + '"' : ' disabled') + '>' + T('vid.prev') + '</button>' +
    '<button id="vidWatchBtn" class="btn ghost vid-watch" type="button"></button>' +
    '<button id="vidNext" class="btn ghost" type="button"' + (next ? ' title="' + esc(next.title) + '"' : ' disabled') + '>' + T('vid.next') + '</button>' +
    '</div></div>' +
    '<div class="row crs-actions"><button id="vidBack" class="btn ghost" type="button">' + T(from ? 'vid.toLesson' : 'vid.toList') + '</button>' +
    (L ? '<button id="vidLevel" class="btn" type="button">' + T('vid.practice') + '</button>' : '') + '</div>';
  view.innerHTML = h;
  mountMedia(v);
  paintWatch(v);
  doc.getElementById('vidWatchBtn').onclick = function () { setWatched(v.id, !watched(v.id)); paintWatch(v); };
  if (prev) doc.getElementById('vidPrev').onclick = function () { open(prev.id); };
  if (next) doc.getElementById('vidNext').onclick = function () { open(next.id); };
  doc.getElementById('vidBack').onclick = function () { if (from && L) openLevel(L); else root.go('videos'); };
  if (L) doc.getElementById('vidLevel').onclick = function () { openLevel(L); };
}
function open(id, opts) {
  from = opts && opts.fromLevel ? { levelId: opts.fromLevel } : null;
  root.location.hash = 'video/' + id;      // app.js render() -> play()
  root.scrollTo(0, 0);
}
function openLevel(L) {
  from = null;
  if (!root.COURSE_UI) return;
  root.go('help', L.id.split('-')[0]);     // draw the course screen, then its lesson
  root.COURSE_UI.openLesson(L);
}

/* ---------- hooks: guided lesson screen, home card ---------- */
function lessonButtons(levelId) {
  var vs = ALL.filter(function (v) { return v.level === levelId; });
  if (!vs.length) return '';
  return '<div class="vid-lesson-btns">' + vs.map(function (v) {
    return '<button type="button" class="btn vid-open" data-vid="' + esc(v.id) + '" data-from="' + esc(levelId) + '">' +
      T('vid.lessonBtn') + (soon(v) ? ' (' + T('vid.soon') + ')' : v.minutes ? ' · ' + minTxt(v) : '') + '</button>';
  }).join('') + '</div>';
}
function homeCard() {
  if (!ALL.length) return '';
  var n = nWatched();
  return '<div class="card vid-home" role="button" tabindex="0" onclick="go(\'videos\')" onkeydown="if(event.key===\'Enter\'||event.key===\' \'){event.preventDefault();go(\'videos\')}">' +
    '<span class="vid-home-ic">🎬</span><div class="vid-home-t"><b>' + T('vid.title').replace(/^🎬\s*/, '') + '</b>' +
    '<span class="progresshint">' + (n ? T('vid.homeProgress', { n: n, m: ALL.length }) : T('vid.homeHint')) + '</span></div>' +
    '<span class="vid-home-go">' + T('vid.homeGo') + '</span></div>';
}

// the lesson screen's video button (delegated: the lesson html is redrawn on every visit)
doc.addEventListener('click', function (e) {
  var b = e.target.closest && e.target.closest('.vid-open');
  if (b) open(b.getAttribute('data-vid'), { fromLevel: b.getAttribute('data-from') });
});
if (!ALL.length) doc.querySelectorAll('.vid-entry').forEach(function (e) { e.style.display = 'none'; });

// deep link: ?video=<ID> (player) · ?videos=1 (list) -> the hash route, before app.js boots
(function () {
  try {
    var p = new URLSearchParams(root.location.search);
    if (p.get('video') && byId(p.get('video'))) root.location.hash = 'video/' + p.get('video');
    else if (p.get('videos')) root.location.hash = 'videos';
  } catch (e) {}
})();

root.VIDEO_UI = { list: list, play: play, open: open, lessonButtons: lessonButtons, homeCard: homeCard, all: ALL, KEY: KEY };

})(typeof window !== 'undefined' ? window : globalThis, typeof document !== 'undefined' ? document : null);
