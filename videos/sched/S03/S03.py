# ---------------------------------------------------------------- numbers (verified)
A = [(0, 5), (1, 7), (2, 3), (3, 1)]
RA = w.run(A, "SJF")
assert RA["gantt"] == [("P1", 0, 5), ("P4", 5, 6), ("P3", 6, 9), ("P2", 9, 16)]
assert RA["wait"] == [0, 8, 4, 2] and RA["avg_wait"] == 3.5
FA = w.run(A, "FCFS")
assert FA["wait"] == [0, 4, 10, 12] and FA["avg_wait"] == 6.5

B = [(0, 4), (2, 6), (5, 1)]
RB = w.run(B, "SJF")
assert RB["gantt"] == [("P1", 0, 4), ("P2", 4, 10), ("P3", 10, 11)]     # at 4 only P2 has arrived
assert [n for n in ("P2", "P3") if B[int(n[1]) - 1][0] <= 4] == ["P2"]

X = [(2, 7), (3, 7), (4, 4), (6, 1)]
RX = w.run(X, "SJF")
assert RX["gantt"] == [("P1", 2, 9), ("P4", 9, 10), ("P3", 10, 14), ("P2", 14, 21)]
assert RX["wait"] == [0, 11, 6, 3] and sum(RX["wait"]) == 20 and RX["avg_wait"] == 5
w.assert_fresh(A, B, X)

