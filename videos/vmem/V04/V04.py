# ---------------------------------------------------------------- numbers (verified)
S = [2, 6, 4, 6, 2, 5, 2, 3, 5, 4]
T = w.rtable("t", S, 3, "OPT", cw=82)
O = T.steps
assert T.faults == 5 and w.faults(S, 3, "LRU") == 6 and w.faults(S, 3, "FIFO") == 7


def nxt(refs, i, p):
    """index of the next use of page p after position i, None if never"""
    return next((j for j in range(i + 1, len(refs)) if refs[j] == p), None)


assert O[5]["victim"] == 6 and {p: nxt(S, 5, p) for p in (2, 6, 4)} == {2: 6, 6: None, 4: 9}
assert O[7]["victim"] == 2 and {p: nxt(S, 7, p) for p in (2, 5, 4)} == {2: None, 5: 8, 4: 9}
assert [i for i, x in enumerate(O) if x["fault"]] == [0, 1, 2, 5, 7]
assert len(set(S)) == T.faults == 5                   # every OPT fault here is a first reference

Y = [6, 3, 6, 1, 5, 3, 1, 6, 3, 1]
E = w.rtable("e", Y, 3, "OPT", cw=78)
assert E.faults == 5
assert E.steps[4]["victim"] == 6 and {p: nxt(Y, 4, p) for p in (6, 3, 1)} == {6: 7, 3: 5, 1: 6}
LY = w.run(Y, 3, "LRU")
assert LY["steps"][4]["victim"] == 3 and LY["steps"][5]["fault"] and LY["faults"] == 6   # LRU evicts 3, needed next
assert E.steps[7]["victim"] == 5 and nxt(Y, 7, 5) is None
assert all(not x["fault"] for x in E.steps[8:])

