# ---------------------------------------------------------------- numbers (verified)
S = [2, 6, 4, 6, 2, 5, 2, 3, 5, 4]
T = w.rtable("t", S, 3, "FIFO", cw=82, order=True)
st_ = T.steps
assert T.faults == 7 and T.sim["hits"] == 3
assert [x["fault"] for x in st_] == [True, True, True, False, False, True, True, True, False, True]
assert st_[4]["mem"] == [2, 6, 4]                       # the hit on 2 left the queue as it was
assert st_[5]["victim"] == 2 and st_[6]["victim"] == 6 and st_[7]["victim"] == 4 and st_[9]["victim"] == 5
assert st_[-1]["slots"] == [4, 2, 3]

X = [3, 7, 1, 3, 5, 2, 3, 6, 7, 1, 3, 2]
E = w.rtable("e", X, 4, "FIFO", cw=72)
ex = E.steps
assert E.faults == 10 and E.sim["hits"] == 2
assert [i for i, s in enumerate(ex) if not s["fault"]] == [3, 10]
assert ex[5]["victim"] == 3 and ex[6]["victim"] == 7       # 3 was hit at reference 4, still the oldest
assert [s["victim"] for s in ex[7:10]] + [ex[11]["victim"]] == [1, 5, 2, 3]
assert sorted(ex[-1]["slots"]) == [1, 2, 6, 7]
assert w.faults(X, 4, "LRU") == 9          # the trap: refreshing 3 on its hit (= LRU) gives another count

