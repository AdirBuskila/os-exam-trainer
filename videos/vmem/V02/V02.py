"""V02 · החלפת דפים FIFO — video script (build: tools/video/vid.py V02).

Source: src/courses/vmem.py level 2 (lesson + goal: when RAM is full the OS picks a victim; FIFO evicts the page
loaded longest ago, and a hit changes nothing in the order; hits + faults = number of references).
Exam part: an original question "בסגנון מבחן" (bank={}): the bank's FIFO-simulation questions are all in quizzes
(2023A-8 is the Belady name), and no free replacement item is a FIFO simulation.
Avoided on purpose: the level-2 quiz strings (1 2 3 1 4 2; 2 3 2 1 5 2 4 5 3 2 5 2; the classic
7 0 1 2 0 3 0 4 2 3 0 3 2 1 2 0 1 7 0 1) and every other string of the course (3 2 1 3 4 1 2; 1 2 3 4 1 2;
1 2 3 4 1 2 5 1 2 3 4 5; the boss 20-reference string).
Here: worked example 2 6 4 6 2 5 2 3 5 4 with 3 frames (7 faults; the same string returns in V03 and V04 for LRU
and OPT), exam-style 3 7 1 3 5 2 3 6 7 1 3 2 with 4 frames (10 faults, ends with 1 2 6 7 in memory).
Every frame column, victim and count comes from sims.replace through w_vmem.run.
"""
from vid import P, Scene, Video, show, hide
