# ---------------------------------------------------------------- numbers (verified)
E1, H1, M1 = w.eat(0.95, 60, 1)
assert (H1, M1) == (60, 120) and abs(E1 - 63) < 1e-9
assert abs(0.95 * 60 - 57) < 1e-9 and abs(0.05 * 120 - 6) < 1e-9

E2, H2, M2 = w.eat(0.9, 40, 2, tlb=2)
assert (H2, M2) == (42, 122) and abs(E2 - 50) < 1e-9
assert abs(0.9 * 42 - 37.8) < 1e-9 and abs(0.1 * 122 - 12.2) < 1e-9
E2_NO_TLB_ON_MISS = 0.9 * 42 + 0.1 * 120                      # the trap: TLB time only on a hit
assert abs(E2_NO_TLB_ON_MISS - 49.8) < 1e-9

# inverse: two levels, 50 ns, EAT 60 -> h = (miss - 60) / (miss - hit)
_, H3, M3 = w.eat(0.5, 50, 2)
assert (H3, M3) == (50, 150)
HR = (M3 - 60) / (M3 - H3)
assert abs(HR - 0.9) < 1e-12 and abs(w.eat(HR, 50, 2)[0] - 60) < 1e-9

Q = BANK["2017B-7"]
