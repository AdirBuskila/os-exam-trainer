"""P05 · ה-TLB וזמן הגישה האפקטיבי — video script (build: tools/video/vid.py P05).

Source: src/courses/paging.py level 5 (lesson + goal: the TLB caches page-table entries; a hit costs one memory
access, a miss costs levels + 1; the effective access time is the weighted average, plus the TLB time on both
sides when it is not negligible).
Exam anchor: 2017B-7 (why prefer the TLB over the full page table: it is faster than an extra memory access), a
free memory item that no guided quiz cites. Official answer as given; it matches the lesson.
Avoided on purpose: every P05 quiz case (80% / 10 ns / two levels = 2026A-8 -> 14; 90% / 100 ns / one level -> 110;
50% / 20 ns / three levels -> 50; 80% / 100 ns / two levels / 5 ns TLB -> 145; the item 2021B-8) and the lesson's
own 80% / 10 ns example. Here: 95% / 60 ns / one level -> 63; 90% / 40 ns / two levels / 2 ns TLB -> 50; and an
exam-style inverse question (two levels, 50 ns, which hit rate gives 60 ns -> 90%).
Every time comes from sims.eat (w_paging.eat also recomputes it by hand) and is asserted.
"""
from vid import P, Scene, Video, show, hide, BANK
